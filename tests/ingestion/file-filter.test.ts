import assert from "node:assert/strict";
import test from "node:test";
import { containsPossibleSecret, decodeSafeText, detectLanguage, filePriority, isRelevantPath, normalizeProjectPath } from "@/lib/ingestion/file-filter";
import { IngestionError } from "@/lib/ingestion/errors";

test("normalizes Windows/Unix separators and dot segments safely", () => {
  assert.equal(normalizeProjectPath(".\\src\\main.ts"), "src/main.ts");
  assert.equal(normalizeProjectPath("src/./main.ts"), "src/main.ts");
});

test("rejects traversal, absolute, drive, ADS, ambiguous and control paths", () => {
  for (const path of ["../x.ts", "a/../x.ts", "/x.ts", "C:\\x.ts", "\\\\server\\x", "src/x.ts:secret", "a/%2e%2e/x.ts", "a\0.ts", "CON.ts", "a./b.ts"]) {
    assert.throws(() => normalizeProjectPath(path), (e) => e instanceof IngestionError && e.code === "UNSAFE_PATH");
  }
});

test("keeps relevant source, manifests, technical docs and unit tests", () => {
  for (const path of ["README.md", "package.json", "src/main.ts", "tests/main.test.ts", "docs/design.md", "requirements.txt", "Dockerfile", "src/app.py", "pom.xml"]) {
    assert.ok(isRelevantPath(path), path);
  }
  assert.ok(filePriority("README.md") < filePriority("src/main.ts"));
  assert.ok(filePriority("package.json") < filePriority("tests/main.test.ts"));
});

test("ignores dependencies, builds, secrets, generated files, media and lockfiles", () => {
  for (const path of ["node_modules/a/index.js", ".git/config", ".next/a.js", "dist/main.js", "build/main.js", "coverage/a.json", "vendor/a.php", ".cache/a.ts", ".env", ".env.local", ".env.example", "nested/.env/README.md", "private.key", "service-account.json", "credentials.json", ".npmrc", "package-lock.json", "src/api.generated.ts", "next-env.d.ts", "bundle.min.js", "image.png"]) {
    assert.equal(isRelevantPath(path), false, path);
  }
});

test("detects requested languages without inferring skill proficiency", () => {
  for (const [ext, language] of Object.entries({js:"JavaScript",ts:"TypeScript",py:"Python",java:"Java",php:"PHP",dart:"Dart",html:"HTML",css:"CSS",json:"JSON",yaml:"YAML",md:"Markdown",go:"Go",rs:"Rust"})) {
    assert.equal(detectLanguage(`main.${ext}`), language);
  }
});

test("content filter rejects binary, invalid UTF8 and embedded secrets regardless of filename", () => {
  for (const bytes of [Buffer.from([0,1,2]), Buffer.from([0xff]), Buffer.from('const password = "unsafe-example";'), Buffer.from("password: fixture-private"), Buffer.from("-----BEGIN PRIVATE KEY-----"), Buffer.from("// @generated do not edit this file")]) {
    assert.equal(decodeSafeText(bytes), undefined);
  }
  assert.ok(containsPossibleSecret('const apiKey = "fixture-not-real";'));
  assert.equal(decodeSafeText(Buffer.from("export const value = 1;\n")), "export const value = 1;\n");
});
